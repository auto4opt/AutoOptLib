struct ComponentMetadata {
  Operation op;
  bool para,archive,choose,update,bit_normal,bit_fastga,point_normal,point_fastga,order,reset,reinit,de;
  bool problem_rng,random_required;
  bool population_context,target_indices;
  explicit ComponentMetadata(const std::string &name):op(operation_kind(name)),
    para(name.rfind("para_",0)==0),archive(name.rfind("archive_",0)==0),
    choose(name.rfind("choose_",0)==0),update(name.rfind("update_",0)==0),
    bit_normal(name.rfind("search_bit_",0)==0),bit_fastga(name.rfind("search_fastga_bit_",0)==0),
    point_normal(name.rfind("cross_point_",0)==0),point_fastga(name.rfind("cross_fastga_",0)==0),
    order(name.rfind("cross_order_",0)==0),reset(name.rfind("search_reset_",0)==0),
    reinit(name.rfind("reinit_",0)==0),de(name.find("_de_")!=std::string::npos),
    population_context(de||op==Operation::search_pso||op==Operation::search_cma||op==Operation::search_eda),
    target_indices(de||op==Operation::search_pso) {
    problem_rng=name=="reinit_continuous"||name=="search_mu_uniform"||name=="search_mu_gaussian"||name=="search_mu_cauchy"||name=="search_eda"||bit_normal||bit_fastga||point_normal||point_fastga||name=="cross_arithmetic"||name=="cross_sim_binary"||name=="search_reset_n"||name=="search_mu_polynomial"||name=="search_ica"||name=="search_cma"||de||name=="choose_elite_fraction"||name=="choose_fastga_proportional"||name=="choose_fastga_stochastic_tournament";
    random_required=name!="choose_traverse"&&name!="choose_ica"&&name!="cross_arithmetic";
    if(update)random_required=name=="update_round_robin"||name=="update_simulated_annealing"||name.find("tournament")!=std::string::npos;
  }
};
